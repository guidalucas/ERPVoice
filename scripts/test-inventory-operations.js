import assert from 'node:assert/strict';
import { InventoryOperationError, validateOperationPlan, operationDigest, productIdentity, inventoryProductFingerprint, planInventoryReceipt } from '../server/inventoryOperations.js';

const context = { businessId: 'shop', actorId: 'actor', permissions: ['inventory:receive'] };
const existing = (itemId = 'one', skuId = 'sku', value = 2) => ({ itemId, type: 'stock.receive', target: { kind: 'existing', skuId }, quantity: { value, unit: 'unit' } });
const plan = (actions = [existing()]) => ({ contractVersion: 1, operationId: 'op', businessId: 'shop', actions });
const product = (overrides = {}) => ({ id: 'sku', name: 'Converter USB to HDMI', stockAvailable: 3, stockReserved: 1, price: 100, ...overrides });
const newAction = (itemId = 'new', sku = { name: 'Other SKU' }) => ({ itemId, type: 'stock.receive', target: { kind: 'new', sku }, quantity: { value: 2, unit: 'unit' } });
const throws = (fn, code) => assert.throws(fn, (error) => error instanceof InventoryOperationError && (!code || error.code === code));
const validated = validateOperationPlan(plan(), context);
assert.deepEqual(validated, plan());
assert.notEqual(validated.actions, plan().actions);
assert.ok(Object.isFrozen(validated.actions[0].quantity));
assert.equal(operationDigest({ ...plan(), source: { channel: 'voice', text: 'hello' } }), operationDigest({ actions: [existing()], businessId: 'shop', operationId: 'op', contractVersion: 1, source: { channel: 'web' } }));
assert.notEqual(operationDigest(plan()), operationDigest(plan([existing('one', 'sku', 3)])));
assert.notEqual(productIdentity(product()), productIdentity(product({ name: 'Converter HDMI to USB' })));
assert.equal(productIdentity(product()), productIdentity(product({ productType: null, productModel: null, size: null, attributes: {}, unit: 'unit' })));
assert.equal(productIdentity(product({ size: 'M' })), productIdentity(product({ attributes: { size: { state: 'known', type: 'text', value: 'm' } } })));
throws(() => productIdentity(product({ size: 'M', attributes: { size: { state: 'known', type: 'text', value: 'l' } } })), 'SKU_IDENTITY_CONFLICT');
assert.equal(inventoryProductFingerprint(product()), inventoryProductFingerprint(product({ price: 200, stockAvailable: 20 })));
assert.notEqual(inventoryProductFingerprint(product()), inventoryProductFingerprint(product({ status: 'inactive' })));

const input = plan([existing(), existing('two')]);
const products = [product({ revision: 7 })];
const snapshot = JSON.stringify({ input, products });
const effects = planInventoryReceipt(input, products);
assert.equal(effects.changedProducts.length, 1);
assert.equal(effects.changedProducts[0].stockAvailable, 7);
assert.equal(effects.changedProducts[0].revision, 7);
assert.deepEqual(effects.items.map((item) => item.stockAvailable), [5, 7]);
assert.deepEqual(effects.movements.map((item) => item.deltaAvailable), [2, 2]);
assert.equal(JSON.stringify({ input, products }), snapshot);
throws(() => planInventoryReceipt(plan([existing('one', 'absent')]), products), 'SKU_NOT_FOUND');
const fingerprintAction = existing();
fingerprintAction.target.expectedFingerprint = inventoryProductFingerprint(products[0]);
assert.equal(planInventoryReceipt(plan([fingerprintAction]), products).items[0].skuId, 'sku');
throws(() => planInventoryReceipt(plan([fingerprintAction]), [product({ name: 'Changed' })]), 'SKU_FINGERPRINT_MISMATCH');
const added = planInventoryReceipt(plan([newAction()]), products, { createId: () => 'new-sku' });
assert.equal(added.changedProducts[0].unit, 'unit');
assert.equal(added.items[0].created, true);
throws(() => planInventoryReceipt(plan([newAction('a'), newAction('b')]), [], { createId: () => 'id' }), 'DUPLICATE_SKU_IDENTITY');
throws(() => planInventoryReceipt(plan([newAction('a', { name: product().name })]), products, { createId: () => 'id' }), 'DUPLICATE_SKU_IDENTITY');
throws(() => planInventoryReceipt(plan(), [product({ stockAvailable: Number.MAX_SAFE_INTEGER })]), 'STOCK_OVERFLOW');
throws(() => planInventoryReceipt(plan(), [product({ unit: 'kg' })]), 'UNIT_MISMATCH');
throws(() => planInventoryReceipt(plan(), [product({ status: 'inactive' })]), 'SKU_INACTIVE');
const priced = (policy, amount = 200, currency = 'USD') => plan([{ ...existing(), price: { amount, currency, policy } }]);
throws(() => planInventoryReceipt(priced('initialize'), products), 'PRICE_CONFLICT');
assert.equal(planInventoryReceipt(priced('initialize'), [product({ price: 0 })]).items[0].price, 200);
assert.equal(planInventoryReceipt(priced('set'), products).items[0].price, 200);
assert.equal(planInventoryReceipt(priced('preserve'), products).items[0].price, 100);
assert.equal(planInventoryReceipt(priced('preserve'), products).items[0].currency, 'XXX');
throws(() => planInventoryReceipt(priced('set'), [product({ priceCurrency: 'EUR' })]), 'CURRENCY_CONFLICT');

for (const bad of [0, -1, 1.5, Number.MAX_SAFE_INTEGER + 1, NaN, Infinity, '2']) throws(() => validateOperationPlan(plan([existing('one', 'sku', bad)]), context), 'INVALID_OPERATION_PLAN');
for (const actions of [[], Array(101).fill(existing()), [existing(), existing()], [undefined]]) throws(() => validateOperationPlan(plan(actions), context));
throws(() => validateOperationPlan({ ...plan(), extra: true }, context));
throws(() => validateOperationPlan({ ...plan(), source: { channel: 'web', text: undefined } }, context));
throws(() => validateOperationPlan(plan([{ ...existing(), type: 'stock.unknown' }]), context), 'UNSUPPORTED_OPERATION');
throws(() => validateOperationPlan(plan(), { ...context, businessId: 'other' }), 'BUSINESS_SCOPE_MISMATCH');
throws(() => validateOperationPlan(plan(), { ...context, businessId: '__default__' }), 'BUSINESS_SCOPE_REQUIRED');
throws(() => validateOperationPlan(plan(), { ...context, actorId: '' }), 'BUSINESS_SCOPE_REQUIRED');
throws(() => validateOperationPlan(plan(), { ...context, permissions: [] }), 'FORBIDDEN');
throws(() => validateOperationPlan(Object.assign(Object.create({}), plan()), context));
throws(() => validateOperationPlan({ ...plan(), actions: Object.assign([existing()], { extra: true }) }, context));
const accessor = plan();
Object.defineProperty(accessor, 'operationId', { get: () => { throw new Error('must not execute'); }, enumerable: true });
throws(() => validateOperationPlan(accessor, context));
throws(() => validateOperationPlan(JSON.parse('{"contractVersion":1,"operationId":"op","businessId":"shop","actions":[],"__proto__":{}}'), context));
throws(() => validateOperationPlan(plan([newAction('new', { name: 'X', attributes: JSON.parse('{"constructor":{"state":"known","type":"text","value":"x"}}') })]), context));
assert.equal(JSON.stringify({ input, products }), snapshot);
console.log('Inventory operation contract and pure receipt planner tests passed');
