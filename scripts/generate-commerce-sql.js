import fs from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { readCommerceMigration } from '../server/commerce/migrationSource.js';

const protectedTables = ['products', 'clients', 'proveedores', 'pedidos', 'transactions', 'inventory_operations', 'inventory_movements'];
const commerceTables = ['inventory_money_policies', 'commerce_profiles', 'commercial_products', 'commercial_product_skus',
  'commercial_product_images', 'commercial_operations', 'commerce_catalogs', 'commercial_publications', 'commerce_schema_migrations', 'commerce_brand_assets'];
const references = [
  ['commercial_products', 'FOREIGN KEY (owner_phone) REFERENCES commerce_profiles(owner_phone)'],
  ['commercial_products', 'FOREIGN KEY (owner_phone, id, cover_image_id) REFERENCES commercial_product_images(owner_phone, commercial_product_id, id)'],
  ['commercial_product_skus', 'FOREIGN KEY (owner_phone, commercial_product_id) REFERENCES commercial_products(owner_phone, id)'],
  ['commercial_product_skus', 'FOREIGN KEY (owner_phone, sku_id) REFERENCES products(owner_phone, id)'],
  ['commercial_product_images', 'FOREIGN KEY (owner_phone, commercial_product_id) REFERENCES commercial_products(owner_phone, id)'],
  ['commercial_operations', 'FOREIGN KEY (owner_phone) REFERENCES commerce_profiles(owner_phone)'],
  ['commerce_catalogs', 'FOREIGN KEY (owner_phone) REFERENCES commerce_profiles(owner_phone)'],
  ['commercial_publications', 'FOREIGN KEY (owner_phone, commercial_product_id) REFERENCES commercial_products(owner_phone, id)'],
];
const literal = value => `'${value.replaceAll("'", "''")}'`;
const sqlArray = values => `ARRAY[${values.map(literal).join(', ')}]`;
const fingerprint = variable => `
  FOREACH table_name IN ARRAY ${sqlArray(protectedTables)} LOOP
    IF to_regclass(format('public.%I', table_name)) IS NOT NULL THEN
      EXECUTE format($fingerprint$
        SELECT jsonb_build_object('count', count(*)::text,
          'hash', md5(COALESCE(string_agg(md5(to_jsonb(t)::text), '' ORDER BY md5(to_jsonb(t)::text)), '')))
        FROM public.%I t
      $fingerprint$, table_name) INTO table_fingerprint;
      ${variable} := ${variable} || jsonb_build_object(table_name, table_fingerprint);
    END IF;
  END LOOP;
`;

export async function buildCommerceSqlBundle() {
  const migrations = await Promise.all([1, 2, 3, 4, 5].map(readCommerceMigration));
  const steps = migrations.map(({ version, sql, checksum, acceptedChecksums }) => `
  -- Migration ${version}; checksum matches the canonical repository source.
  SELECT checksum INTO previous_checksum FROM public.commerce_schema_migrations WHERE version = ${version};
  IF FOUND THEN
    IF NOT (previous_checksum = ANY(${sqlArray(acceptedChecksums)})) THEN
      RAISE EXCEPTION 'MIGRATION_CHECKSUM_MISMATCH: version ${version}';
    END IF;
  ELSE
${sql.split('\n').map(line => line.trim() ? `    ${line.trimEnd()}` : '').join('\n')}
    INSERT INTO public.commerce_schema_migrations(version, checksum) VALUES (${version}, '${checksum}');
  END IF;
`).join('\n');
  return `-- FullMatch Studio: run the COMPLETE file in the Stocky project's Supabase SQL Editor.
-- Check the selected project and its backup before running. No credentials are needed here.
-- Generated by npm run commerce:schema:sql; do not edit this generated file.
-- Adds schema only: does not enable businesses, infer currency, seed demo data or publish products.
-- One transaction; a failure rolls everything back. Known migrations are safe to run again.
BEGIN;
SET LOCAL search_path = public, pg_catalog;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '45s';

DO $fullmatch_schema$
DECLARE
  table_name text;
  role_name text;
  previous_checksum text;
  table_fingerprint jsonb;
  before_fingerprints jsonb := '{}'::jsonb;
  after_fingerprints jsonb := '{}'::jsonb;
  required_reference record;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('stocky:commerce:migration'));
  IF to_regclass('public.products') IS NULL THEN
    RAISE EXCEPTION 'INVENTORY_FOUNDATION_REQUIRED: select the existing Stocky database';
  END IF;
${fingerprint('before_fingerprints')}
  CREATE TABLE IF NOT EXISTS public.commerce_schema_migrations (
    version INTEGER PRIMARY KEY, checksum TEXT NOT NULL, applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
${steps}
  FOREACH table_name IN ARRAY ${sqlArray(commerceTables)} LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC', table_name);
    FOR role_name IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated') LOOP
      EXECUTE format('REVOKE ALL ON TABLE public.%I FROM %I', table_name, role_name);
    END LOOP;
  END LOOP;

  FOR required_reference IN SELECT * FROM (VALUES
    ${references.map(([table, definition]) => `(${literal(table)}, ${literal(definition.replace(/\s|"/g, ''))})`).join(',\n    ')}
  ) AS required(table_name, definition) LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = 'public' AND c.relname = required_reference.table_name AND k.contype = 'f'
        AND left(replace(regexp_replace(pg_get_constraintdef(k.oid), '[[:space:]"]', '', 'g'), 'public.', ''),
          length(required_reference.definition)) = required_reference.definition
    ) THEN RAISE EXCEPTION 'COMMERCE_SCHEMA_NOT_READY: missing reference on %', required_reference.table_name;
    END IF;
  END LOOP;
  IF EXISTS (
    SELECT 1 FROM pg_roles r CROSS JOIN pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relname = ANY(${sqlArray(commerceTables)})
      AND r.rolname IN ('anon', 'authenticated')
      AND (has_table_privilege(r.oid, c.oid, 'SELECT') OR has_table_privilege(r.oid, c.oid, 'INSERT')
        OR has_table_privilege(r.oid, c.oid, 'UPDATE') OR has_table_privilege(r.oid, c.oid, 'DELETE')
        OR has_table_privilege(r.oid, c.oid, 'TRUNCATE') OR has_table_privilege(r.oid, c.oid, 'REFERENCES')
        OR has_table_privilege(r.oid, c.oid, 'TRIGGER'))
  ) THEN RAISE EXCEPTION 'COMMERCE_SCHEMA_NOT_READY: API roles retain access'; END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_index i WHERE i.indexrelid = to_regclass('public.idx_commercial_operations_library')
      AND i.indisvalid AND position('(owner_phone,operation_type,created_atDESC,operation_idDESC)'
        in replace(pg_get_indexdef(i.indexrelid), ' ', '')) > 0
  ) THEN RAISE EXCEPTION 'CONTENT_SCHEMA_NOT_READY'; END IF;
${fingerprint('after_fingerprints')}
  IF before_fingerprints IS DISTINCT FROM after_fingerprints THEN
    RAISE EXCEPTION 'MIGRATION_DATA_MISMATCH: existing inventory data changed; rolling back';
  END IF;
END
$fullmatch_schema$;
COMMIT;

-- Success: versions 1, 2, 3 and 4. Business/profile enablement is a separate step.
SELECT version, applied_at FROM public.commerce_schema_migrations
WHERE version IN (1, 2, 3, 4) ORDER BY version;
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = new URL('../docs/fullmatch/SUPABASE_COMMERCIAL_SCHEMA.sql', import.meta.url);
  const sql = await buildCommerceSqlBundle();
  if (process.argv.includes('--check')) {
    if ((await fs.readFile(file, 'utf8')).replace(/\r\n/g, '\n') !== sql) throw new Error('COMMERCE_SQL_BUNDLE_OUTDATED');
    console.log('Commercial SQL bundle matches migrations.');
  } else {
    await fs.writeFile(file, sql);
    console.log('Generated docs/fullmatch/SUPABASE_COMMERCIAL_SCHEMA.sql (no database connection).');
  }
}
