  await api(fixture.token, rolePath, 'PATCH', { role: 'admin', expectedRole: 'member' }, 404);
  await api(fixture.member.token, prefix + '/products/' + product.id, 'GET', undefined, 403);
  assert.deepEqual(errors, []);
  console.log('PASS: failures restore the stored role; demotion blocks reads, writes and receipt replay with the same token; removed members cannot regain access');
