  await select.selectOption('member');
  await expect(ownerPage.getByText(/ahora es miembro y ya no puede gestionar Studio/)).toBeVisible();
  assert.equal((await api(fixture.member.token, '/api/auth/me')).role, 'member');
  await api(fixture.member.token, prefix + '/setup', 'GET', undefined, 403);
  await api(fixture.member.token, prefix + '/products/' + product.id, 'GET', undefined, 403);
  await api(fixture.member.token, prefix + '/products/' + product.id, 'PATCH', edit, 403);
  await assert.rejects(service.summary(forgedContext), { code: 'COMMERCE_FORBIDDEN' });
  await openTeam(adminPage);
  await adminPage.getByRole('button', { name: 'Cerrar', exact: true }).click();
  await adminPage.getByRole('button', { name: 'Más', exact: true }).click();
  assert.equal(await adminPage.getByRole('menu', { name: 'Más secciones' }).getByRole('link', { name: 'Stocky Studio', exact: true }).count(), 0);
